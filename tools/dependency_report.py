"""Generate the M01 module dependency report and public API inventory (M01-T15/T16).

Scans idle_farmer/core and idle_farmer/data, independently of Godot, and writes
artifacts/M01/M01_Dependency_Report.md:
  - module (folder) dependency table and Mermaid diagram,
  - per-class dependencies on other project classes,
  - any reference from core/data to classes outside core/data (must be none),
  - public API inventory (class_name, base, public funcs and static funcs with signatures).

    python -I tools/dependency_report.py
"""

import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]
PROJECT = ROOT / "idle_farmer"
OUT = ROOT / "artifacts" / "M01" / "M01_Dependency_Report.md"
AUDITED = ["core", "data"]

CLASS_RX = re.compile(r"^class_name\s+(\w+)", re.M)
EXTENDS_RX = re.compile(r"^extends\s+(\w+)", re.M)
FUNC_RX = re.compile(r"^(static\s+)?func\s+([A-Za-z]\w*)\s*\(([^)]*)\)\s*(->\s*[^:]+)?:", re.M)
STRING_RX = re.compile(r'"(?:[^"\\]|\\.)*"')


def strip(source: str) -> str:
    lines = []
    for line in source.splitlines():
        line = STRING_RX.sub('""', line)
        if "#" in line:
            line = line[: line.index("#")]
        lines.append(line)
    return "\n".join(lines)


def all_classes() -> dict[str, pathlib.Path]:
    classes = {}
    for path in PROJECT.rglob("*.gd"):
        if "addons" in path.parts:
            continue
        m = CLASS_RX.search(path.read_text(encoding="utf-8"))
        if m:
            classes[m.group(1)] = path
    return classes


def module_of(path: pathlib.Path) -> str:
    rel = path.relative_to(PROJECT)
    return "/".join(rel.parts[:2]) if len(rel.parts) > 2 else rel.parts[0]


def main() -> None:
    classes = all_classes()
    audited = sorted(p for d in AUDITED for p in (PROJECT / d).rglob("*.gd"))
    class_deps: dict[str, set[str]] = {}
    module_deps: dict[str, set[str]] = {}
    outside: list[str] = []
    api: list[tuple[str, str, str, list[str]]] = []
    for path in audited:
        source = path.read_text(encoding="utf-8")
        code = strip(source)
        name_m = CLASS_RX.search(source)
        name = name_m.group(1) if name_m else path.stem
        base_m = EXTENDS_RX.search(source)
        base = base_m.group(1) if base_m else "?"
        refs = set()
        for other, other_path in classes.items():
            if other != name and re.search(rf"\b{other}\b", code):
                refs.add(other)
                if not any(other_path.is_relative_to(PROJECT / d) for d in AUDITED):
                    outside.append(f"{path.relative_to(PROJECT)} -> {other} ({other_path.relative_to(PROJECT)})")
                else:
                    mod_a, mod_b = module_of(path), module_of(other_path)
                    if mod_a != mod_b:
                        module_deps.setdefault(mod_a, set()).add(mod_b)
        class_deps[name] = refs
        funcs = []
        for m in FUNC_RX.finditer(source):
            static, fname, params, ret = m.groups()
            funcs.append(f"{'static ' if static else ''}{fname}({' '.join(params.split())}){(' ' + ret.strip()) if ret else ''}")
        api.append((name, base, str(path.relative_to(PROJECT)).replace("\\", "/"), funcs))

    modules = sorted({module_of(p) for p in audited})
    lines = [
        "# M01 — Module dependency report and public API inventory",
        "",
        "Generated by `tools/dependency_report.py`, a static scan of `idle_farmer/core` and `idle_farmer/data` that is independent of Godot. "
        "The enforcing check is `tests/architecture/test_core_dependencies.gd` (V09). Comments and string literals are ignored.",
        "",
        "## References from core/data to classes outside core/data",
        "",
        "**None.**" if not outside else "\n".join(f"- {o}" for o in outside),
        "",
        "## Module dependencies",
        "",
        "| Module | Depends on |",
        "|---|---|",
    ]
    for mod in modules:
        lines.append(f"| `{mod}` | {', '.join(f'`{d}`' for d in sorted(module_deps.get(mod, set()))) or '—'} |")
    lines += ["", "```mermaid", "graph LR"]
    for mod in modules:
        for dep in sorted(module_deps.get(mod, set())):
            lines.append(f"  {mod.replace('/', '_')}[{mod}] --> {dep.replace('/', '_')}[{dep}]")
    lines += ["```", "", "## Public API inventory", "",
              "Public functions only; names starting with `_` are internal. Signatures are copied from source.", ""]
    for name, base, rel, funcs in sorted(api, key=lambda a: a[2]):
        deps = ", ".join(sorted(class_deps[name])) or "—"
        lines.append(f"### `{name}` (extends `{base}`) — `{rel}`")
        lines.append("")
        lines.append(f"Uses: {deps}")
        lines.append("")
        for f in funcs:
            lines.append(f"- `{f}`")
        if not funcs:
            lines.append("- (data/constants only)")
        lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {OUT}: {len(audited)} scripts, {len(outside)} outside references")
    if outside:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
