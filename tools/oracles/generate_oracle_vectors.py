"""Independent test-oracle vectors for M01 (build plan P5/P6, M01-V05/V13).

Python integers are arbitrary precision, so these values do not share any code path with the
GDScript implementation. Regenerate after changing a vector set:

    python -I tools/oracles/generate_oracle_vectors.py

Writes idle_farmer/tests/fixtures/oracle_vectors.gd.
"""

import hashlib
import pathlib
import random

INT64_MAX = 2**63 - 1
INT64_MIN = -(2**63)

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "idle_farmer" / "tests" / "fixtures" / "oracle_vectors.gd"

# FRS §5.1 levels 1-30 and §5.1.1 option B parameters.
EXPLICIT = [
    0, 240, 650, 1300, 2300, 3600, 5200, 7300, 10000, 13500,
    18000, 24000, 29334, 34667, 40000, 50000, 60000, 70000, 88750, 107500,
    126250, 145000, 181250, 217500, 253750, 290000, 347500, 405000, 462500, 520000,
]
FIRST_INCREMENT = 57_500


def ceil_div(a: int, d: int) -> int:
    return -((-a) // d)


def xp_thresholds() -> list[int]:
    thresholds = list(EXPLICIT)
    inc = FIRST_INCREMENT
    while thresholds[-1] + inc <= INT64_MAX:
        thresholds.append(thresholds[-1] + inc)
        inc = inc + ceil_div(inc * 10, 100)
    return thresholds


def closed_form_adversary(level: int) -> int:
    # A plausible but wrong implementation: one rounding of a float geometric series.
    return EXPLICIT[-1] + sum(round(FIRST_INCREMENT * 1.1 ** (k - 31)) for k in range(31, level + 1))


def mul_div_cases() -> list[tuple[int, int, int]]:
    m = INT64_MAX
    return [
        (0, 5, 7), (7, 0, 3), (10, 10, 3), (16, 12_500, 10_000), (270, 1_500, 10_000),
        (480_000_000, 4_000, 10_000), (3_600_000_000, 4_000, 10_000), (1, 1, 10_000),
        (m, 1, 1), (m, 10_000, 10_000), (m, 9_999, 10_000), (m, 3, 4),
        (2**62, 3, 4), (m, m, m), (m - 1, m - 2, m), (m, 2, 3),
        (123_456_789_012_345_678, 98_765, 4_321), (2**40 + 17, 2**40 + 29, 2**31 - 1),
        (m, 3, 2), (m, m, 1), (2**62, 4, 3), (m, 10_001, 10_000),
    ] + random_overflowing_cases()


def random_overflowing_cases() -> list[tuple[int, int, int]]:
    """Seeded cases whose a*b overflows int64, forcing the decomposed slow path."""
    rng = random.Random(20261030)
    cases = []
    while len(cases) < 120:
        a = rng.randrange(2**32, 2**63)
        b = rng.randrange(2**32, 2**63)
        if a * b <= INT64_MAX:
            continue
        # Divisors from tiny to near int64, so both representable and unrepresentable quotients occur.
        d = rng.choice([rng.randrange(1, 2**16), rng.randrange(2**16, 2**40), rng.randrange(2**40, 2**63)])
        cases.append((a, b, d))
    return cases


def codec_encode(v) -> bytes:
    if v is None:
        return b"n"
    if v is True:
        return b"t"
    if v is False:
        return b"f"
    if isinstance(v, int):
        return b"i" + str(v).encode("ascii")
    if isinstance(v, str):
        raw = v.encode("utf-8")
        return b"s" + str(len(raw)).encode("ascii") + b":" + raw
    if isinstance(v, list):
        return b"[" + b",".join(codec_encode(x) for x in v) + b"]"
    if isinstance(v, dict):
        items = sorted(v.items(), key=lambda kv: kv[0])
        return b"{" + b",".join(codec_encode(k) + b":" + codec_encode(x) for k, x in items) + b"}"
    raise TypeError(type(v))


CODEC_CASES = [
    None, True, False, 0, -1, INT64_MAX, INT64_MIN, "", "wheat", "Ünïcode ✓",
    [], {}, [1, "a", None, [True, False]],
    {"b": 2, "a": 1, "B": 3, "_": 4},
    {"plots": [{"plot_id": 1, "unlocked": True, "cycle": None}], "coins": INT64_MAX, "save_id": "s"},
]


def gd_literal(v) -> str:
    if v is None:
        return "null"
    if v is True:
        return "true"
    if v is False:
        return "false"
    if isinstance(v, int):
        return "(-9223372036854775807 - 1)" if v == INT64_MIN else str(v)
    if isinstance(v, str):
        return '"' + v.replace("\\", "\\\\").replace('"', '\\"') + '"'
    if isinstance(v, list):
        return "[" + ", ".join(gd_literal(x) for x in v) + "]"
    if isinstance(v, dict):
        return "{" + ", ".join(f"{gd_literal(k)}: {gd_literal(x)}" for k, x in v.items()) + "}"
    raise TypeError(type(v))


def main() -> None:
    thresholds = xp_thresholds()
    assert len(thresholds) == 349
    lines = [
        "class_name OracleVectors",
        "extends RefCounted",
        "## GENERATED by tools/oracles/generate_oracle_vectors.py (independent Python oracle). Do not edit.",
        "",
        "## Cumulative XP for levels 1..N, N = last level whose threshold fits in int64.",
        "const XP_THRESHOLDS: Array[int] = [",
    ]
    for i in range(0, len(thresholds), 6):
        lines.append("\t" + ", ".join(str(t) for t in thresholds[i:i + 6]) + ",")
    lines.append("]")
    nxt_inc = FIRST_INCREMENT
    t = EXPLICIT[-1]
    for _ in range(31, len(thresholds) + 1):
        t += nxt_inc
        nxt_inc = nxt_inc + ceil_div(nxt_inc * 10, 100)
    lines.append(f'## First mathematical threshold beyond int64 (level {len(thresholds) + 1}), as a string.')
    lines.append(f'const FIRST_UNREPRESENTABLE_THRESHOLD: String = "{t + nxt_inc}"')
    lines.append("")
    lines.append("## [level, closed-form float adversary value] that a correct per-step-ceil curve must NOT equal.")
    lines.append("const XP_CLOSED_FORM_ADVERSARY: Array[Array] = [")
    for level in (35, 40):
        adv = closed_form_adversary(level)
        assert adv != thresholds[level - 1]
        lines.append(f"\t[{level}, {adv}],")
    lines.append("]")
    lines.append("")
    lines.append("## [a, b, d, ok, floor(a*b/d), ceil(a*b/d)]; ok == false when the quotient exceeds int64.")
    lines.append("const MUL_DIV: Array[Array] = [")
    for a, b, d in mul_div_cases():
        fl = (a * b) // d
        ce = ceil_div(a * b, d)
        ok = ce <= INT64_MAX
        lines.append(f"\t[{a}, {b}, {d}, {'true' if ok else 'false'}, {fl if ok else 0}, {ce if ok else 0}],")
    lines.append("]")
    lines.append("")
    lines.append("## [value, canonical encoding as UTF-8 text, SHA-256 hex of the encoding]")
    lines.append("const CODEC: Array[Array] = [")
    for v in CODEC_CASES:
        enc = codec_encode(v)
        text = enc.decode("utf-8")
        lines.append(f"\t[{gd_literal(v)}, {gd_literal(text)}, \"{hashlib.sha256(enc).hexdigest()}\"],")
    lines.append("]")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(thresholds)} thresholds)")


if __name__ == "__main__":
    main()
